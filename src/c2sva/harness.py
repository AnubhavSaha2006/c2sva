"""Emit the formal harness (observer-style Verilog for open-source Yosys/SBY) and an SVA view.

Environment (what the caller of the HLS block may do):
  * reset in the first cycle only, with ap_start low; ap_continue held high (ap_ctrl_chain);
  * ap_start is held until ap_ready; inputs are held stable while the call reads them;
  * sequential mode: a new call starts only after the previous ap_done;
    overlap mode (top-level pipelining, read-only memories): a new call may be accepted on
    every ap_ready; calls complete in order, so a FIFO of captured inputs is popped on ap_done.
Memory models (one storage element per C array element; any layout via Memory.locate):
  * ap_memory / reshaped words / partition banks: 1-cycle registered read, word writes; as in
    Vitis' co-simulation RAM model, a read of an address the other port writes in the same
    cycle returns the new data, and when both ports write one address port 1 wins;
  * bram mode: byte address, byte-enable writes;
  * complete partition / single objects: input port = pre-state value, output+valid = writes.
Views used by the properties:  {a}_s{i} pre-state at call start, {a}_e{i} post-state,
  {a}_o{i} snapshot taken at call start (\\old);  {x}_now / {x}_c scalar at start / of the
  completing call;  h_res_c result of the completing call.
No property mentions a cycle count. Termination is checked only by the separate latency
harness (term_only=True), whose bound is used solely as the BMC depth.
"""
import math


def _ext(sig, width, signed, W):
    if width >= W:
        return sig
    return f"{{{{{W - width}{{{sig}[{width - 1}]}}}}, {sig}}}" if signed else f"{{{W - width}'d0, {sig}}}"


def _views(w, name, sig, width, signed, W, layout=None):
    """Emit the W-bit view `name` of signal `sig`; for structs one view per field
    (`name__field`) plus a full-width raw view (used by frame conditions)."""
    if not layout:
        w(f"  wire signed [{W - 1}:0] {name} = {_ext(sig, width, signed, W)};")
        return
    w(f"  wire [{width - 1}:0] {name} = {sig};")
    for f, off, fw, fs in layout:
        sl = f"{name}_raw__{f}"
        w(f"  wire [{fw - 1}:0] {sl} = {sig}[{off + fw - 1}:{off}];")
        w(f"  wire signed [{W - 1}:0] {name}__{f} = {_ext(sl, fw, fs, W)};")


def written(itf):
    for m in itf.memories.values():
        if any(b.ports.get(k) for b in m.banks for k in ("we0", "we1")) or any(c.vld_port for c in m.cells):
            return True
    return any(o.vld_port for o in itf.objects.values())


def overlap_mode(itf, term_only=False, force_seq=False):
    return bool(itf.control.get("overlap")) and not term_only and not force_seq and not written(itf)


def generate(fn, itf, props, tr, W, lat_max=None, term_only=False, fifo_depth=8, force_seq=False):
    C = itf.control
    clk, rst, start, done = C["clk"], C["rst"], C["start"], C["done"]
    ready = C.get("ready")
    ovl = overlap_mode(itf, term_only, force_seq)
    pmap = {p.name: p for p in fn.params}
    L = []
    w = L.append

    # ---------------- ports of the harness = free inputs of the environment
    ins = [f"input {clk}", f"input {start}"] + ([f"input {rst}"] if rst else [])
    if C.get("cont"):
        ins.append(f"input {C['cont']}")
    for c, port in itf.scalars.items():
        ins.append(f"input [{pmap[c].width - 1}:0] {port}")
    objs = list(itf.objects.values()) + [c for m in itf.memories.values() for c in m.cells]
    for ob in objs:
        if ob.in_port:
            ins.append(f"input [{ob.width - 1}:0] {ob.in_port}")
    w(f"// Generated by c2sva from the ACSL contract of {fn.name} ({itf.tool} RTL, "
      f"{'latency search' if term_only else 'overlapping calls' if ovl else 'sequential calls'}). Do not edit.")
    w(f"module harness({', '.join(ins)});")
    w(f"  wire {done};")
    for x in ("idle", "ready"):
        if C.get(x):
            w(f"  wire {C[x]};")
    conns = [f".{p}({p})" for p in ((clk,) if C.get("clk_port", True) else ()) + ((rst,) if rst else ())
             + (start, done) + tuple(C[x] for x in ("idle", "ready", "cont") if C.get(x))]
    if itf.ret:
        w(f"  wire [{itf.ret_width - 1}:0] {itf.ret};")
        conns.append(f".{itf.ret}({itf.ret})")
    conns += [f".{p}({p})" for p in itf.scalars.values()]

    # ---------------- call tracking
    w(f"  reg h_init = 1; always @(posedge {clk}) h_init <= 0;")
    w("  reg h_done_d = 0;")
    if ovl:
        w(f"  // overlap mode: a call is accepted when ap_start && ap_ready")
        w(f"  wire h_start_evt = !h_init && {start} && {ready};")
        w(f"  reg [7:0] h_cnt = 0;            // calls in flight")
        w(f"  wire h_busy = h_cnt != 0;")
    else:
        w("  reg h_busy = 0, h_ready_seen = 0; reg [15:0] h_cyc = 0;")
        w(f"  wire h_start_evt = !h_init && {start} && !h_busy;")

    # ---------------- memories
    for a, mem in itf.memories.items():
        dw = mem.width
        lay = mem.protocol + (f", partition {mem.partition}" if mem.partition else "") + \
            (f", reshape {mem.reshape}" if mem.reshape else "")
        w(f"  // memory {a}[{mem.size}]  ({lay})")
        for i in range(mem.size):
            init = "(* anyinit, keep *) " if mem.protocol != "cells" or not mem.cells[i].in_port else "(* keep *) "
            # keep: the C replay reads every cell from the trace, used by a property or not
            w(f"  {init}reg [{dw - 1}:0] m_{a}_{i}; (* keep *) reg [{dw - 1}:0] o_{a}_{i};")
        if mem.protocol == "cells":
            for i, cell in enumerate(mem.cells):
                for x, wd in ((cell.out_port, dw), (cell.vld_port, 1)):
                    if x:
                        w(f"  wire [{wd - 1}:0] {x};")
                        conns.append(f".{x}({x})")
                if cell.in_port:
                    conns.append(f".{cell.in_port}({cell.in_port})")
            w(f"  always @(posedge {clk}) begin")
            for i, cell in enumerate(mem.cells):
                pre = cell.in_port or f"m_{a}_{i}"
                w(f"    if (h_start_evt) o_{a}_{i} <= {pre};")
                if cell.vld_port:
                    w(f"    if ({cell.vld_port}) m_{a}_{i} <= {cell.out_port};")
                    w(f"    else if (h_start_evt) m_{a}_{i} <= {pre};")
                else:
                    w(f"    if (h_start_evt) m_{a}_{i} <= {pre};")
            w("  end")
            lay = pmap[a].layout
            for i, cell in enumerate(mem.cells):
                pre = cell.in_port or f"m_{a}_{i}"
                _views(w, f"{a}_s{i}", pre, dw, mem.signed, W, lay)
                _views(w, f"{a}_e{i}", f"m_{a}_{i}", dw, mem.signed, W, lay)
                _views(w, f"{a}_o{i}", f"o_{a}_{i}", dw, mem.signed, W, lay)
            continue
        for b, bank in enumerate(mem.banks):
            P = bank.ports
            for n in ("0", "1"):
                if "address" + n in P:
                    w(f"  wire [{bank.aw - 1}:0] {P['address' + n]};")
                if "ce" + n in P:
                    w(f"  wire {P['ce' + n]};")
                if "we" + n in P:
                    w(f"  wire [{bank.wen_bits - 1}:0] {P['we' + n]};")
                if "d" + n in P:
                    w(f"  wire [{bank.word_width - 1}:0] {P['d' + n]};")
                if "q" + n in P:
                    w(f"  reg  [{bank.word_width - 1}:0] {P['q' + n]} = 0;")
            for key in ("Clk_A", "Rst_A", "Clk_B", "Rst_B"):
                port = f"{a}_{key}"
                if port in itf.ports:
                    w(f"  wire {port};")
                    conns.append(f".{port}({port})")
            conns += [f".{v}({v})" for v in P.values()]
        lay = pmap[a].layout
        for i in range(mem.size):
            _views(w, f"{a}_s{i}", f"m_{a}_{i}", dw, mem.signed, W, lay)
            _views(w, f"{a}_e{i}", f"m_{a}_{i}", dw, mem.signed, W, lay)
            _views(w, f"{a}_o{i}", f"o_{a}_{i}", dw, mem.signed, W, lay)
        w(f"  always @(posedge {clk}) begin")
        for i in range(mem.size):
            w(f"    m_{a}_{i} <= m_{a}_{i};")
            w(f"    if (h_start_evt) o_{a}_{i} <= m_{a}_{i};")
        for b, bank in enumerate(mem.banks):
            P = bank.ports
            words = {}
            for i in range(mem.size):
                bb, word, slot = mem.locate(i)
                if bb == b:
                    words.setdefault(word, {})[slot] = i
            shift = int(math.log2(bank.word_width // 8)) if bank.byte_addr else 0
            for n in ("0", "1"):
                ad = P.get("address" + n)
                if not ad:
                    continue
                wa = f"({ad} >> {shift})" if shift else ad
                if "q" + n in P and "ce" + n in P:
                    rd = f"{bank.word_width}'d0"
                    for word, slots in sorted(words.items(), reverse=True):
                        parts = [f"m_{a}_{slots[s]}" if s in slots else f"{mem.width}'d0"
                                 for s in reversed(range(mem.slots))]
                        val = "{" + ", ".join(parts) + "}" if len(parts) > 1 else parts[0]
                        rd = f"({wa} == {word} ? {val} : {rd})"
                    w(f"    if ({P['ce' + n]}) {P['q' + n]} <= {rd};")
                    # Vitis' RAM model (AESL_automem): a read on one port of an address that
                    # the other port writes in the same cycle returns the NEW data (per byte)
                    o = "1" if n == "0" else "0"
                    if all(k + o in P for k in ("ce", "we", "d", "address")):
                        wao = f"({P['address' + o]} >> {shift})" if shift else P["address" + o]
                        hit = f"{P['ce' + n]} && {P['ce' + o]} && {wao} == {wa}"
                        if bank.wen_bits > 1:
                            for byte in range(bank.wen_bits):
                                w(f"    if ({hit} && {P['we' + o]}[{byte}]) {P['q' + n]}[{8 * byte + 7}:{8 * byte}] <= "
                                  f"{P['d' + o]}[{8 * byte + 7}:{8 * byte}];")
                        else:
                            w(f"    if ({hit} && {P['we' + o]}) {P['q' + n]} <= {P['d' + o]};")
                if "we" + n in P:
                    ce, we, d = P["ce" + n], P["we" + n], P["d" + n]
                    for word, slots in words.items():
                        for s, i in slots.items():
                            lo = s * mem.width
                            if bank.wen_bits > 1:
                                nb = mem.width // 8
                                for byte in range(nb):
                                    bl = lo + 8 * byte
                                    w(f"    if ({ce} && {we}[{bl // 8}] && {wa} == {word}) "
                                      f"m_{a}_{i}[{8 * byte + 7}:{8 * byte}] <= {d}[{bl + 7}:{bl}];")
                            else:
                                w(f"    if ({ce} && {we} && {wa} == {word}) m_{a}_{i} <= {d}[{lo + mem.width - 1}:{lo}];")
        w("  end")

    # ---------------- single objects realized as ports
    for a, ob in itf.objects.items():
        w(f"  // object {a} ({ob.kind})")
        for x, wd in ((ob.out_port, ob.width), (ob.vld_port, 1)):
            if x:
                w(f"  wire [{wd - 1}:0] {x};")
                conns.append(f".{x}({x})")
        if ob.in_port:
            conns.append(f".{ob.in_port}({ob.in_port})")
        w(f"  (* anyinit, keep *) reg [{ob.width - 1}:0] m_{a}_0; (* keep *) reg [{ob.width - 1}:0] o_{a}_0;")
        pre = ob.in_port or f"m_{a}_0"
        w(f"  always @(posedge {clk}) begin")
        w(f"    if (h_start_evt) o_{a}_0 <= {pre};")
        if ob.vld_port:
            w(f"    if ({ob.vld_port}) m_{a}_0 <= {ob.out_port};")
            w(f"    else if (h_start_evt) m_{a}_0 <= {pre};" if ob.in_port else f"    else m_{a}_0 <= m_{a}_0;")
        elif ob.in_port:
            w(f"    if (h_start_evt) m_{a}_0 <= {ob.in_port};")
        w("  end")
        lay = pmap[a].layout
        _views(w, f"{a}_s0", pre, ob.width, ob.signed, W, lay)
        _views(w, f"{a}_e0", f"m_{a}_0", ob.width, ob.signed, W, lay)
        _views(w, f"{a}_o0", f"o_{a}_0", ob.width, ob.signed, W, lay)

    w(f"  {itf.module} dut({', '.join(conns)});")

    # ---------------- captured inputs/result of the call that completes
    for c in itf.scalars:
        w(f"  reg [{pmap[c].width - 1}:0] {c}_cap = 0;")
    if itf.ret:
        w(f"  reg [{itf.ret_width - 1}:0] h_res_cap = 0;")
    if ovl:
        D = fifo_depth
        for c, port in itf.scalars.items():
            w(f"  reg [{pmap[c].width - 1}:0] {c}_q [0:{D - 1}];")
        w(f"  reg [7:0] h_head = 0, h_tail = 0;")
        w(f"  always @(posedge {clk}) begin")
        w(f"    h_done_d <= !h_init && {done};")
        w("    if (!h_init) begin")
        w(f"      h_cnt <= h_cnt + (h_start_evt ? 1 : 0) - ({done} ? 1 : 0);")
        w(f"      if (h_start_evt) h_tail <= (h_tail + 1) % {D};")
        w(f"      if ({done}) h_head <= (h_head + 1) % {D};")
        for c, port in itf.scalars.items():
            w(f"      if (h_start_evt) {c}_q[h_tail] <= {port};")
            w(f"      if ({done}) {c}_cap <= (h_cnt == 0) ? {port} : {c}_q[h_head];")
        if itf.ret:
            w(f"      if ({done}) h_res_cap <= {itf.ret};")
        w("    end")
        w("  end")
    else:
        rdy = ready or "1'b1"
        w(f"  always @(posedge {clk}) begin")
        w(f"    h_done_d <= !h_init && {done};")
        w("    if (!h_init) begin")
        w(f"      if (h_start_evt && !{done}) begin h_busy <= 1; h_cyc <= 1; h_ready_seen <= {rdy}; end")
        w(f"      else if (h_busy && {done}) begin h_busy <= 0; h_cyc <= 0; end")
        w(f"      else if (h_busy) begin h_cyc <= h_cyc + 1; if ({rdy}) h_ready_seen <= 1; end")
        for c, port in itf.scalars.items():
            w(f"      if (h_start_evt) {c}_cap <= {port};")
        if itf.ret:
            w(f"      if ({done}) h_res_cap <= {itf.ret};")
        w("    end")
        w("  end")
    for c, port in itf.scalars.items():
        p = pmap[c]
        w(f"  wire [{p.width - 1}:0] {c}_nowr = h_start_evt ? {port} : {c}_cap;")
        _views(w, f"{c}_now", c + "_nowr", p.width, p.signed, W, p.layout)
        _views(w, f"{c}_c", c + "_cap", p.width, p.signed, W, p.layout)
    if itf.ret:
        _views(w, "h_res_c", "h_res_cap", fn.ret_width, fn.ret_signed, W, fn.ret_layout)
    for name, width in tr.anyconst:
        sg = 'signed ' if width > 1 else ''
        if name.startswith("q_"):
            # witness of a universally meant quantifier in an assertion: one per trace is exact
            w(f"  (* anyconst *) reg {sg}[{width - 1}:0] {name};")
        else:
            # out-of-model cells and recursion cut-off values: chosen afresh for every call (a
            # trace-wide constant would tie the assumptions of different calls together, i.e.
            # make the environment stronger); held from acceptance to completion
            w(f"  (* anyseq *) reg {sg}[{width - 1}:0] {name}_n; reg {sg}[{width - 1}:0] {name}_r = 0;")
            w(f"  always @(posedge {clk}) if (h_start_evt) {name}_r <= {name}_n;")
            w(f"  wire {sg}[{width - 1}:0] {name} = h_start_evt ? {name}_n : {name}_r;")

    # ---------------- environment
    w("  always @(*) begin")
    if rst:
        rst_on = f"!{rst}" if C["rst_active_low"] else rst
        w(f"    if (h_init) assume({rst_on}); else assume(!({rst_on}));")
    w(f"    if (h_init) assume(!{start});                    // no call is started during reset")
    if C.get("cont"):
        w(f"    assume({C['cont']});")
    if not ovl:
        if ready:
            w(f"    if (h_busy && !h_ready_seen) assume({start});      // hold ap_start until ap_ready")
            w(f"    if (h_busy && h_ready_seen) assume(!{start});")
        else:
            w(f"    if (h_busy) assume(!{start});")
    lines = {}
    for p in props:
        if p.kind in ("term", "discharged"):
            continue
        if p.kind in ("access", "access_phys") and ovl:
            continue
        w(f"    // {p.id} {p.source}")
        if p.kind == "assume":
            w(f"    if (h_start_evt) assume({p.cond});")
            continue
        if term_only:
            continue
        guard = {"post": "h_done_d", "access": "(h_busy || h_start_evt)", "access_phys": "(h_busy || h_start_evt)",
                 "protocol": "1'b1"}[p.kind]
        if p.kind in ("access", "access_phys"):
            w("`ifdef CHECK_ACCESS" if p.kind == "access" else "`ifdef CHECK_PHYS")
        else:
            # the memory-access runs check only their own assertions (a functional violation
            # must not be reported as an access finding, and it would redo the functional BMC)
            w("`ifndef C2SVA_ACCESS_ONLY")
        lines[len(L) + 1] = p.id
        w(f"    if ({guard}) assert({p.cond});")
        w("`endif")
    if term_only:
        lines[len(L) + 1] = "TERM"
        w(f"    if (h_busy) assert(h_cyc <= {lat_max});        // latency search only")
    elif ovl:
        lines[len(L) + 1] = "PROTO"
        w(f"    if (!h_init && {done}) assert(h_cnt != 0 || h_start_evt);   // no ap_done without a call")
        lines[len(L) + 1] = "FIFO"
        w(f"    assert(h_cnt < {fifo_depth});                      // model capacity: calls in flight")
    w("    cover(h_done_d);")
    w("  end")
    stable = list(itf.scalars.values()) + [ob.in_port for ob in objs if ob.in_port]
    if ovl:
        # a call that has been requested (ap_start high, not yet ap_ready) keeps ap_start high
        # until it is accepted (combinational assumption on this cycle)
        w(f"  reg h_wait = 0; always @(posedge {clk}) h_wait <= !h_init && {start} && !{ready};")
        w(f"  always @(*) if (!h_init && h_wait) assume({start});")
    if stable:
        if ovl:
            w(f"  always @(posedge {clk}) if (!h_init && h_wait) begin   // inputs held until accepted")
        else:
            w(f"  always @(posedge {clk}) if (!h_init && h_busy) begin")
        for s in stable:
            w(f"    assume({s} == $past({s}));")
        w("  end")
    w("endmodule")

    S = [f"// SVA view of the {fn.name} contract on {itf.tool} RTL (helper signals as in harness.sv)",
         f"default clocking @(posedge {clk}); endclocking"]
    for p in props:
        S.append(f"// {p.id} {p.source}" + (f"   [{'; '.join(p.notes)}]" if p.notes else ""))
        S.append({"assume": f"assume property (h_start_evt |-> {p.cond});",
                  "post": f"assert property (h_done_d |-> {p.cond});",
                  "access": f"assert property ((h_busy || h_start_evt) |-> {p.cond});  // access check",
                  "access_phys": f"assert property ((h_busy || h_start_evt) |-> {p.cond});  // physical bound",
                  "protocol": f"assert property ({p.cond});",
                  "term": f"assert property (h_start_evt |-> s_eventually {done});   // checked bounded",
                  "discharged": "// discharged by construction (no property needed)"}[p.kind])
    return "\n".join(L) + "\n", "\n".join(S) + "\n", lines
