#!/usr/bin/env python3
"""Build a GitHub-style 'files changed' page: Vitis RTL unchanged, c2sva additions in green."""
import difflib, hashlib, html, os, re, sys

D = os.path.expanduser("~/cbv/runs/DEMO_find/cases/Nonmutating__find/vitis/base/original")
REL = "runs/DEMO_find/cases/Nonmutating__find/vitis/base/original"
OUT = sys.argv[1]

def rd(p): return open(os.path.join(D, p)).read().splitlines()
def md5(p): return hashlib.md5(open(os.path.join(D, p), "rb").read()).hexdigest()

KW = r"\b(module|endmodule|input|output|wire|reg|always|posedge|if|else|begin|end|assume|assert|cover|property|logic|integer|for|return|const|size_type|value_type|initial|ifdef|endif|connect|read|prep|setundef|hierarchy|flatten|proc)\b"
def hl(line):
    s = html.escape(line)
    m = re.search(r"(//.*|/\*.*|^\s*\*.*|^#.*|^\[.*\]$)", s)
    head, tail = (s[:m.start()], s[m.start():]) if m else (s, "")
    head = re.sub(KW, r'<b class="kw">\1</b>', head)
    return head + (f'<span class="cm">{tail}</span>' if tail else "")

def row(kind, a, b, text, note=None):
    sign = {"add": "+", "del": "-", "ctx": " ", "ref": " "}[kind]
    r = (f'<tr class="{kind}"><td class="ln">{a or ""}</td><td class="ln">{b or ""}</td>'
         f'<td class="sg">{sign}</td><td class="tx">{hl(text) or "&nbsp;"}</td></tr>')
    if note:
        r += f'<tr class="note"><td colspan="3"></td><td><div class="n">{html.escape(note)}</div></td></tr>'
    return r

def new_file(lines, notes={}, ref=()):
    return "".join(row("ref" if i in ref else "add", None, i, l, notes.get(i))
                   for i, l in enumerate(lines, 1)), len(lines), 0

def same_file(lines):
    return "".join(row("ctx", i, i, l) for i, l in enumerate(lines, 1)), 0, 0

def diff_file(a, b, notes={}, ctx=3):
    out, ad, de = [], 0, 0
    for g in difflib.SequenceMatcher(None, a, b, autojunk=False).get_grouped_opcodes(ctx):
        i1, j1 = g[0][1] + 1, g[0][3] + 1
        out.append(f'<tr class="hunk"><td colspan="3"></td><td>@@ -{i1},{g[-1][2]-g[0][1]} +{j1},{g[-1][4]-g[0][3]} @@</td></tr>')
        for tag, a1, a2, b1, b2 in g:
            if tag == "equal":
                out += [row("ctx", a1+k+1, b1+k+1, a[a1+k]) for k in range(a2-a1)]
            else:
                out += [row("del", a1+k+1, None, a[a1+k]) for k in range(a2-a1)]
                out += [row("add", None, b1+k+1, b[b1+k], notes.get(b1+k+1)) for k in range(b2-b1)]
                de += a2-a1; ad += b2-b1
    return "".join(out), ad, de

def nth(lines, pat):
    return next(i for i, l in enumerate(lines, 1) if pat in l)

files = []
def add(fid, path, status, body, ad, de, desc, open_=True, extra=""):
    files.append(dict(id=fid, path=path, status=status, body=body, ad=ad, de=de, desc=desc, open=open_, extra=extra))

# 1. the one source change
a, b = rd("src/find.c"), rd("src/hls_src/find.c")
add("csrc", "src/find.c → src/hls_src/find.c", "modified", *diff_file(a, b, {4: "Only source change: the pointer gets its array size so Vitis can map it to a 4-word RAM port. The code and its ACSL annotations are untouched."}, ctx=20),
    "C input to Vitis HLS. The contract (find.h) and loop annotations are kept as written.")

# 2. Vitis RTL, unchanged
for f, fid in (("hls/proj/sol/syn/verilog/find.v", "findv"), ("hls/proj/sol/syn/verilog/find_flow_control_loop_pipe.v", "pipev")):
    h = md5(f)
    add(fid, f, "unchanged", *same_file(rd(f)),
        "Generated by Vitis HLS 2026.1. c2sva never edits it: every proof reads this exact file.",
        open_=False, extra=f'<div class="md5">md5 {h} · identical copy checked in formal/check_yices_bmc/src/{os.path.basename(f)}</div>')

# 3. harness.sv, new
h = rd("formal/harness.sv")
hn = {
    1: "Generated from the ACSL contract. Wraps the Vitis module; does not change it.",
    nth(h, "wire h_start_evt"): "Q1: a call starts on the ap_start/ap_ready handshake. requires clauses are assumed here.",
    nth(h, "find dut("): "The Vitis module, instantiated as is (grey line: a reference, not new logic).",
    nth(h, "h_done_d <="): "Q1/Q3: a call completes on ap_done, whatever the latency. ensures clauses are asserted here.",
    nth(h, "if (h_init) assume(ap_rst)"): "Environment: reset first, then no call starts during reset.",
    nth(h, "assert(((72'sd0 <= h_res_c)"): "P1  ensures 0 <= \\result <= \\old(n)",
}
for i, l in enumerate(h, 1):
    if "if (h_start_evt) o_a_0 <=" in l: hn[i] = "\\old(a[0]): snapshot register taken at call start."
    if "a_q0 <=" in l and i not in hn and "a_ce0" in l: hn[i] = "Q4: RAM model, one symbolic register per cell, 1-cycle read like the Vitis BRAM, with write forwarding."
add("harness", "formal/harness.sv", "added", *new_file(h, hn, ref={nth(h, "find dut(")}),
    "Environment, memory model, \\old snapshots and the assertions, around the unchanged Vitis module.")

# 4. props.sva
add("props", "props.sva", "added", *new_file(rd("props.sva"), {3: "Each assertion keeps its ACSL clause as a comment, so it can be traced back."}),
    "SVA view of the same properties (for reading and for commercial tools).")

# 5. SBY script
s = rd("formal/check_yices.sby")
add("sby", "formal/check_yices.sby", "added", *new_file(s, {
    nth(s, "read -formal find.v"): "Reads the Vitis file directly from its HLS output folder (see [files] below).",
    nth(s, "setundef -zero"): "FPGA power-on: registers without reset start at 0, applied to the Vitis modules only.",
    nth(s, "bmc: depth"): "Q3: BMC depth comes from the latency bound established formally (16 cycles here), never from a guess."}),
    "SymbiYosys script: BMC, access check, physical bound, cover, latency search.", open_=False)

# 6. A1 harness: diff against harness.sv
b = rd("formal/prove/harness_inv.sv")
an = {nth(b, "A1: taps"): "A1: taps on internal Vitis registers. They are read through Yosys `connect` (see p.sby), so the RTL text stays unchanged."}
for i, l in enumerate(b, 1):
    if "ap_sig_allocacmp_i_1" in l and "t_18" in l: an[i] = "C loop counter i lives in this Vitis register; the C loop invariant 0 <= i <= n is checked on it."
add("inv", "formal/prove/harness_inv.sv  (compared with formal/harness.sv)", "added", *diff_file(h, b, an),
    "A1 unbounded proof harness: sequential calls, taps, certified invariants. Red lines are harness.sv lines this variant replaces; neither file is RTL.", open_=False)

# 7. prove script
p = rd("formal/prove/kind_inv_k4/p.sby")
add("psby", "formal/prove/kind_inv_k4/p.sby", "added", *new_file(p, {
    nth(p, "connect -nounset -set t_0"): "Connects harness wires to Vitis internals inside Yosys. No Verilog line is edited.",
    nth(p, "mode prove"): "k-induction with the 78 certified invariants: PASS at k = 4."}),
    "A1 proof script (k-induction with invariants).", open_=False)

# 8. variants
for f, d in (("formal/harness_acc.sv", "Access-check variant (C2SVA_ACCESS_ONLY)."), ("formal/harness_lat.sv", "Latency-search variant.")):
    add(os.path.basename(f).split(".")[0], f + "  (compared with formal/harness.sv)", "added", *diff_file(h, rd(f)), d, open_=False)

# ---- page
tot_a = sum(f["ad"] for f in files if f["status"] != "modified")
rtl_lines = sum(len(rd(f)) for f in ("hls/proj/sol/syn/verilog/find.v", "hls/proj/sol/syn/verilog/find_flow_control_loop_pipe.v"))
badge = {"added": "new", "unchanged": "unchanged", "modified": "1 line"}
def bar(ad, de):
    n = ad + de
    if n == 0: return '<span class="bar">' + '<i class="z"></i>' * 5 + "</span>"
    g = round(5 * ad / n); return '<span class="bar">' + '<i class="g"></i>' * g + '<i class="r"></i>' * (5 - g) + "</span>"

listing = "".join(
    f'<li><a href="#{f["id"]}"><span class="st {f["status"]}">{badge[f["status"]]}</span>'
    f'<span class="p">{html.escape(f["path"])}</span>'
    f'<span class="cnt">{"<em class=a>+" + str(f["ad"]) + "</em>" if f["ad"] else ""} {"<em class=d>−" + str(f["de"]) + "</em>" if f["de"] else ""}{"<em class=u>0 changes</em>" if f["status"]=="unchanged" else ""}</span>{bar(f["ad"], f["de"])}</a></li>'
    for f in files)
blocks = "".join(
    f'<details class="file" id="{f["id"]}"{" open" if f["open"] else ""}><summary>'
    f'<span class="st {f["status"]}">{badge[f["status"]]}</span><span class="p">{html.escape(f["path"])}</span>'
    f'<span class="cnt">{"<em class=a>+" + str(f["ad"]) + "</em>" if f["ad"] else ""} {"<em class=d>−" + str(f["de"]) + "</em>" if f["de"] else ""}</span></summary>'
    f'<p class="desc">{html.escape(f["desc"])}</p>{f["extra"]}<div class="scroll"><table class="diff">{f["body"]}</table></div></details>'
    for f in files)

page = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "template.html")).read()
page = (page.replace("%%LIST%%", listing).replace("%%BLOCKS%%", blocks)
        .replace("%%ADD%%", str(tot_a)).replace("%%RTL%%", str(rtl_lines)).replace("%%REL%%", REL)
        .replace("%%MD5%%", md5("hls/proj/sol/syn/verilog/find.v")))
open(OUT, "w").write(page)
print("wrote", OUT, len(page), "bytes; additions", tot_a)
